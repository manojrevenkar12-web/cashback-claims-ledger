import { api } from '../../shared/api.ts'
import { euros, percent } from '../../shared/format.ts'
import type { Report } from '../../shared/types.ts'
import { useResource } from '../../shared/useResource.ts'
import { EmptyState, ErrorState, Skeleton } from '../../shared/ui/States.tsx'
import styles from './Results.module.css'

const ORDER = ['desk', 'support_all', 'rules_alone', 'llm_alone']
const LEDGER_ORDER = ['ledger', 'arrival_order', 'dedupe_only']
const LEDGER_LABELS: Record<string, string> = {
  ledger: 'Keep every fact, compute from the set',
  arrival_order: 'Apply each event as it arrives',
  dedupe_only: 'Drop repeated ids, then apply in arrival order',
}

export function ReportTables({ report }: { report: Report }) {
  const designs = report.claims.designs
  return (
    <>
      <table className={styles.table}>
        <caption>
          {report.world.claims.toLocaleString()} missing-cashback claims from {report.world.shoppers.toLocaleString()}{' '}
          shoppers, the same claims and the same luck for every design
        </caption>
        <thead>
          <tr>
            <th scope="col">Design</th>
            <th scope="col">Decided right</th>
            <th scope="col">Invalid claims sent to networks</th>
            <th scope="col">Valid cashback denied</th>
            <th scope="col">Support hours</th>
          </tr>
        </thead>
        <tbody>
          {ORDER.filter((k) => designs[k]).map((k) => {
            const d = designs[k]
            return (
              <tr key={k} className={k === 'desk' ? styles.ours : undefined}>
                <th scope="row">{d.label}</th>
                <td>
                  <span className={styles.bar}>
                    <span className={styles.fill} style={{ inlineSize: percent(d.rightShare) }} />
                  </span>
                  {percent(d.rightShare)}
                </td>
                <td>{percent(d.invalidFiledShare)}</td>
                <td>{euros(d.validDeniedCents)}</td>
                <td>{d.supportHours.toLocaleString()}</td>
              </tr>
            )
          })}
        </tbody>
      </table>
      <table className={styles.table}>
        <caption>
          Balances after {report.ledger.eventsDelivered.toLocaleString()} deliveries, of which{' '}
          {report.ledger.repeatedDeliveries.toLocaleString()} were repeats and{' '}
          {report.ledger.outOfOrderDeliveries.toLocaleString()} arrived out of order
        </caption>
        <thead>
          <tr>
            <th scope="col">Consumer</th>
            <th scope="col">Users exact to the cent</th>
            <th scope="col">Cents off in total</th>
            <th scope="col">Rewards in the wrong state</th>
          </tr>
        </thead>
        <tbody>
          {LEDGER_ORDER.filter((k) => report.ledger.designs[k]).map((k) => {
            const l = report.ledger.designs[k]
            return (
              <tr key={k} className={k === 'ledger' ? styles.ours : undefined}>
                <th scope="row">{LEDGER_LABELS[k]}</th>
                <td>{percent(l.usersExactShare)}</td>
                <td>{euros(l.centsOff)}</td>
                <td>{l.wrongStatus.toLocaleString()}</td>
              </tr>
            )
          })}
        </tbody>
      </table>
    </>
  )
}

export function ResultsView() {
  const { data, error, loading, retry } = useResource(() => api.results(), [])
  return (
    <section className={styles.view} aria-label="Results">
      <h1 className={styles.title}>How the desk compares</h1>
      <p className={styles.lede}>
        Measured on a simulated platform: shoppers, shops, three affiliate networks, a card scheme and the people who
        file claims. Generated by the evaluation, not typed in.
      </p>
      {loading && !data ? <Skeleton label="Loading results" /> : null}
      {error ? <ErrorState what="The results" message={error} onRetry={retry} /> : null}
      {data && !data.dev ? (
        <EmptyState title="No report yet." hint="Run ./gradlew :eval:evaluate and restart the service." />
      ) : null}
      {data?.dev ? <ReportTables report={data.dev} /> : null}
      {data?.heldout ? (
        <>
          <h2 className={styles.subtitle}>Held-out world, run once</h2>
          <ReportTables report={data.heldout} />
        </>
      ) : null}
    </section>
  )
}
