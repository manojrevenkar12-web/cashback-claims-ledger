package cashback.eval;

import cashback.common.Json;
import cashback.product.ledger.Fact;
import cashback.world.Model.Claim;
import cashback.world.Model.Click;
import cashback.world.Model.Event;
import cashback.world.World;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * The service's demo data: a small world's clicks, delivered events and filed claims, in the shapes the platform
 * receives them. Nothing of the world's truth goes in. One busy shopper becomes {@code u-demo}, the shopper key's user.
 */
final class Seed {

    private Seed() {
    }

    static Map<String, Object> build(Path root) {
        Map<String, Object> cfg = Json.read(root.resolve("config/world.json"));
        cfg.put("seed", "demo-seed");
        cfg.put("shoppers", 220L);
        World w = new World(Json.read(root.resolve("config/terms.json")), cfg);
        String busiest = w.claims.stream().filter(c -> !c.fraud())
            .collect(java.util.stream.Collectors.groupingBy(Claim::userId, java.util.stream.Collectors.counting()))
            .entrySet().stream().max(Map.Entry.comparingByValue()).map(Map.Entry::getKey).orElse("u-00000");
        List<Object> clicks = new ArrayList<>();
        for (Click c : w.clicks) {
            Map<String, Object> m = new LinkedHashMap<>();
            m.put("clickId", c.clickId());
            m.put("userId", rename(c.userId(), busiest));
            m.put("merchantId", c.shopId());
            m.put("atMillis", c.atMillis());
            clicks.add(m);
        }
        List<Object> events = new ArrayList<>();
        for (Event e : w.events) {
            Map<String, Object> fact = Fact.encode(Wiring.fact(e.fact()));
            fact.put("userId", rename((String) fact.get("userId"), busiest));
            Map<String, Object> m = new LinkedHashMap<>();
            m.put("deliveredAtMillis", e.deliveredAtMillis());
            m.put("fact", fact);
            events.add(m);
        }
        List<Object> tickets = new ArrayList<>();
        for (Claim c : w.claims) {
            Map<String, Object> t = Wiring.ticket(c).toJson();
            t.put("userId", rename(c.userId(), busiest));
            tickets.add(t);
        }
        Map<String, Object> out = new LinkedHashMap<>();
        out.put("_about", "Generated by ./gradlew :eval:seed from a small simulated world. Platform inputs only.");
        out.put("clicks", clicks);
        out.put("events", events);
        out.put("tickets", tickets);
        return out;
    }

    private static String rename(String user, String busiest) {
        return user.equals(busiest) ? "u-demo" : user;
    }
}
